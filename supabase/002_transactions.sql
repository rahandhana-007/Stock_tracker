create table if not exists public.transactions (
  id           bigint generated by default as identity primary key,
  item_id      bigint not null references public.items(id) on delete cascade,
  posting_date date not null,
  year         integer generated always as (extract(year from posting_date)::int) stored,
  month        integer generated always as (extract(month from posting_date)::int) stored,
  seq          integer not null default 0,          -- urutan baris di laporan SAP (untuk saldo berjalan)
  doc_type     text not null default '',            -- SO, PD, SI, PR, IM, PU, MR, ...
  doc_no       text not null default '',            -- "SO 1234"
  whse         text not null default '',
  acct_name    text not null default '',            -- G/L Acct / BP Name
  rec_qty      numeric not null default 0,
  iss_qty      numeric not null default 0,
  uom          text not null default '',
  balance      numeric,                             -- saldo setelah transaksi menurut SAP
  role         text not null default 'auto',        -- actual | incoming | return | ignore | auto
  imported_at  timestamptz not null default now()
);
create index if not exists transactions_item_date_idx on public.transactions(item_id, posting_date, seq);
create index if not exists transactions_item_year_idx on public.transactions(item_id, year, month);

alter table public.transactions enable row level security;
drop policy if exists "authenticated full access" on public.transactions;
create policy "authenticated full access" on public.transactions for all to authenticated using (true) with check (true);
grant select, insert, update, delete on public.transactions to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- ---------------------------------------------------------------- import_transactions(jsonb)
-- p = {"year":2026, "from_month":1, "to_month":8, "replace":true, "codes":["15008", ...],
--      "rows":[{"code":"15008","posting_date":"2026-01-05","seq":1,"doc_type":"SO","doc_no":"SO 123",
--               "whse":"01","acct_name":"...","rec_qty":0,"iss_qty":750,"uom":"Kgs","balance":500,"role":"actual"}]}
-- replace=true → hapus dulu transaksi item-item "codes" pada tahun & rentang bulan tsb (dipanggil pada chunk pertama).
create or replace function public.import_transactions(p jsonb)
returns jsonb
language plpgsql security invoker as $$
declare
  v_year int := (p->>'year')::int;
  v_from int := coalesce((p->>'from_month')::int, 1);
  v_to   int := coalesce((p->>'to_month')::int, 12);
  n_del  int := 0;
  n_ins  int := 0;
begin
  if v_year is null then raise exception 'Tahun tidak valid'; end if;

  if coalesce((p->>'replace')::boolean, false) then
    delete from public.transactions t
    using public.items i
    where t.item_id = i.id
      and i.code in (select jsonb_array_elements_text(coalesce(p->'codes', '[]'::jsonb)))
      and t.year = v_year and t.month between v_from and v_to;
    get diagnostics n_del = row_count;
  end if;

  insert into public.transactions(item_id, posting_date, seq, doc_type, doc_no, whse, acct_name, rec_qty, iss_qty, uom, balance, role)
  select i.id, (r->>'posting_date')::date, coalesce((r->>'seq')::int, 0),
         coalesce(r->>'doc_type', ''), coalesce(r->>'doc_no', ''), coalesce(r->>'whse', ''), coalesce(r->>'acct_name', ''),
         coalesce((r->>'rec_qty')::numeric, 0), coalesce((r->>'iss_qty')::numeric, 0), coalesce(r->>'uom', ''),
         (r->>'balance')::numeric, coalesce(r->>'role', 'auto')
  from jsonb_array_elements(coalesce(p->'rows', '[]'::jsonb)) r
  join public.items i on i.code = r->>'code';
  get diagnostics n_ins = row_count;

  return jsonb_build_object('deleted', n_del, 'inserted', n_ins);
end $$;

revoke all on function public.import_transactions(jsonb) from public, anon;
grant execute on function public.import_transactions(jsonb) to authenticated;

notify pgrst, 'reload schema';
