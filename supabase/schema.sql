-- ---------------------------------------------------------------- tabel
create table if not exists public.items (
  id             bigint generated by default as identity primary key,
  code           text not null unique,
  category       text not null default '',
  description    text not null default '',
  uom            text not null default '',
  min_stock      numeric not null default 0,
  max_stock      numeric not null default 0,
  lead_time_days integer,
  user_dept      text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.item_years (
  item_id       bigint not null references public.items(id) on delete cascade,
  year          integer not null,
  opening_stock numeric not null default 0,
  primary key (item_id, year)
);

create table if not exists public.monthly (
  item_id  bigint not null references public.items(id) on delete cascade,
  year     integer not null,
  month    integer not null check (month between 1 and 12),
  forecast numeric,
  actual   numeric,
  incoming numeric,
  primary key (item_id, year, month)
);
create index if not exists monthly_year_idx on public.monthly(year);

create table if not exists public.settings (
  key   text primary key,
  value text
);

create table if not exists public.import_logs (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  user_email  text,
  format      text,
  filename    text,
  options     jsonb,
  result      jsonb
);

