-- ---------------------------------------------------------------- daftar tahun fiskal
create or replace function public.list_years()
returns setof integer
language sql stable security invoker as $$
  select distinct year from (
    select year from public.monthly
    union
    select year from public.item_years
  ) s order by 1;
$$;

-- ---------------------------------------------------------------- apply_changes(jsonb)
-- Satu transaksi untuk: edit sel, tempel baris, stok awal, import Master, import SAP.
-- payload:
-- {
--   "year": 2026,
--   "replace_year": false,            -- true = hapus semua data bulanan & stok awal tahun tsb dulu
--   "items": [{
--     "code": "15008",
--     "create": true,                 -- buat item bila belum ada (false = lewati item yang tidak ada)
--     "update_fields": false,         -- true = timpa field master item yang sudah ada dengan "fields"
--     "fields": {"category": "...", "description": "...", "uom": "...", "min_stock": 0, "max_stock": 0, "lead_time_days": null, "user_dept": "..."},
--     "fill_uom": "Kg",               -- isi UoM hanya bila masih kosong
--     "opening": 1250,                -- stok awal tahun tsb (opsional)
--     "cells": [{"month": 1, "actual": 750, "incoming": 750}]  -- key yang ada ditulis (null = kosongkan), key yang tidak ada dibiarkan
--   }]
-- }
create or replace function public.apply_changes(p jsonb)
returns jsonb
language plpgsql security invoker as $$
declare
  v_year   int := (p->>'year')::int;
  it       jsonb;
  c        jsonb;
  f        jsonb;
  v_id     bigint;
  v_uom    text;
  n_created int := 0; n_updated int := 0; n_skipped int := 0; n_open int := 0; n_cells int := 0;
begin
  if v_year is null or v_year < 2000 or v_year > 2100 then
    raise exception 'Tahun tidak valid';
  end if;

  if coalesce((p->>'replace_year')::boolean, false) then
    delete from public.monthly    where year = v_year;
    delete from public.item_years where year = v_year;
  end if;

  for it in select * from jsonb_array_elements(coalesce(p->'items', '[]'::jsonb)) loop
    f := coalesce(it->'fields', '{}'::jsonb);
    select id, uom into v_id, v_uom from public.items where code = it->>'code';

    if v_id is null then
      if not coalesce((it->>'create')::boolean, false) then
        n_skipped := n_skipped + 1;
        continue;
      end if;
      insert into public.items(code, category, description, uom, min_stock, max_stock, lead_time_days, user_dept)
      values (
        it->>'code',
        coalesce(f->>'category', ''),
        coalesce(nullif(f->>'description', ''), it->>'code'),
        coalesce(f->>'uom', ''),
        coalesce((f->>'min_stock')::numeric, 0),
        coalesce((f->>'max_stock')::numeric, 0),
        (f->>'lead_time_days')::int,
        coalesce(f->>'user_dept', '')
      ) returning id into v_id;
      n_created := n_created + 1;
    else
      if coalesce((it->>'update_fields')::boolean, false) then
        update public.items set
          category       = coalesce(f->>'category', category),
          description    = coalesce(nullif(f->>'description', ''), description),
          uom            = coalesce(f->>'uom', uom),
          min_stock      = coalesce((f->>'min_stock')::numeric, min_stock),
          max_stock      = coalesce((f->>'max_stock')::numeric, max_stock),
          lead_time_days = case when f ? 'lead_time_days' then (f->>'lead_time_days')::int else lead_time_days end,
          user_dept      = coalesce(f->>'user_dept', user_dept)
        where id = v_id;
      elsif nullif(it->>'fill_uom', '') is not null and coalesce(v_uom, '') = '' then
        update public.items set uom = it->>'fill_uom' where id = v_id;
      end if;
      n_updated := n_updated + 1;
    end if;

    if it ? 'opening' and jsonb_typeof(it->'opening') = 'number' then
      insert into public.item_years(item_id, year, opening_stock)
      values (v_id, v_year, (it->>'opening')::numeric)
      on conflict (item_id, year) do update set opening_stock = excluded.opening_stock;
      n_open := n_open + 1;
    end if;

    for c in select * from jsonb_array_elements(coalesce(it->'cells', '[]'::jsonb)) loop
      insert into public.monthly(item_id, year, month, forecast, actual, incoming)
      values (v_id, v_year, (c->>'month')::int, (c->>'forecast')::numeric, (c->>'actual')::numeric, (c->>'incoming')::numeric)
      on conflict (item_id, year, month) do update set
        forecast = case when c ? 'forecast' then excluded.forecast else public.monthly.forecast end,
        actual   = case when c ? 'actual'   then excluded.actual   else public.monthly.actual   end,
        incoming = case when c ? 'incoming' then excluded.incoming else public.monthly.incoming end;
      n_cells := n_cells + 1;
    end loop;
  end loop;

  return jsonb_build_object('created', n_created, 'updated', n_updated, 'skipped', n_skipped,
                            'opening_set', n_open, 'cells', n_cells, 'year', v_year);
end $$;

-- ---------------------------------------------------------------- rollover tahun
-- Stok awal p_to = End Stock Desember p_from (opening + Σ incoming − Σ actual) untuk semua item.
create or replace function public.rollover_year(p_from int, p_to int, p_copy_forecast boolean default false)
returns jsonb
language plpgsql security invoker as $$
declare n int;
begin
  if p_from = p_to then
    raise exception 'Tahun asal dan tujuan harus berbeda';
  end if;
  insert into public.item_years(item_id, year, opening_stock)
  select i.id, p_to,
         coalesce(iy.opening_stock, 0) + coalesce(sum(coalesce(m.incoming, 0) - coalesce(m.actual, 0)), 0)
  from public.items i
  left join public.item_years iy on iy.item_id = i.id and iy.year = p_from
  left join public.monthly m on m.item_id = i.id and m.year = p_from
  group by i.id, iy.opening_stock
  on conflict (item_id, year) do update set opening_stock = excluded.opening_stock;
  get diagnostics n = row_count;
  if p_copy_forecast then
    insert into public.monthly(item_id, year, month, forecast)
    select item_id, p_to, month, forecast from public.monthly where year = p_from
    on conflict (item_id, year, month) do update set forecast = excluded.forecast;
  end if;
  return jsonb_build_object('ok', true, 'items', n, 'to_year', p_to);
end $$;

